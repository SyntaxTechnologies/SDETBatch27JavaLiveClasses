package org.example.class5;

/*
Print a Square of Stars
Use nested for loops to print:
***
***
***
 */

public class P7 {
    static void main() {


        for(int i=0;i<3;i++){
            for(int j=0;j<3;j++){
                System.out.print("*");
            }
            System.out.println();
        }


    }
}
