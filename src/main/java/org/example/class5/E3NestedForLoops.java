package org.example.class5;

public class E3NestedForLoops {
    static void main() {

        for(int i=0;i<10;i++){
            System.out.print("*");
        }
        System.out.println();
        for(int i=0;i<10;i++){
            System.out.print("*");
        }

        System.out.println();
        for(int i=0;i<10;i++){
            System.out.print("*");
        }

        System.out.println();
        for(int i=0;i<10;i++){
            System.out.print("*");
        }

        System.out.println();
        for(int i=0;i<10;i++){
            System.out.print("*");
        }
    }
}
