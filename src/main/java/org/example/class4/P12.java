package org.example.class4;

/*
Store and Print 5 Numbers
Write a Java program to store 5 numbers in an array and print them one by one.
 */
public class P12 {
    static void main() {

        int[] numbers = {20, 33, 44, 55, 70};
        for (int i = 0; i < numbers.length; i++) {
            System.out.println(numbers[i]);
        }
    }
}
