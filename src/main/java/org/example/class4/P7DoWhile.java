package org.example.class4;

/*
Print Your Name 3 Times
Write a Java program using a Do while loop to print your name 3 times
 */
public class P7DoWhile {
    static void main() {


        int i = 0;
        do {
            System.out.println("Muhammad Asghar");
            i++;
        } while (i < 3);


    }
}
