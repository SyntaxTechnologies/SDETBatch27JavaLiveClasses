package org.example.class4;
/*
Print First and Last Element
Write a Java program to store 5 integers in an array and print the first and last element.

Example:
If the array is {10, 20, 30, 40, 50}
 */
public class P13 {
    static void main() {

        int[] number={10,20,30,44,50};
        System.out.println(number[0]);
        System.out.println(number[number.length-1]);
    }
}
